#!/usr/bin/env python3
"""Create the fully translated synthetic PS2 performance workload."""

import argparse
import struct
from pathlib import Path


ENTRY = 0x9000
LEAF = 0x9080
SOURCE = 0x12000
DESTINATION = 0x13000


def r(rs: int, rt: int, rd: int, function: int, sa: int = 0) -> int:
    return (rs << 21) | (rt << 16) | (rd << 11) | (sa << 6) | function


def i(op: int, rs: int, rt: int, immediate: int) -> int:
    return (op << 26) | (rs << 21) | (rt << 16) | (immediate & 0xFFFF)


def mmi(rs: int, rt: int, rd: int, sub: int, function: int) -> int:
    return (0x1C << 26) | (rs << 21) | (rt << 16) | (rd << 11) | (sub << 6) | function


def j(op: int, target: int) -> int:
    return (op << 26) | ((target >> 2) & 0x03FFFFFF)


def build_words() -> tuple[int, ...]:
    words = [
        r(4, 0, 16, 0x21),       # addu  s0,a0,zero (outer count)
        i(0x0F, 0, 17, 1),       # lui   s1,0x0001
        i(0x0D, 17, 17, 0x2000), # ori   s1,s1,0x2000
        i(0x0F, 0, 18, 1),       # lui   s2,0x0001
        i(0x0D, 18, 18, 0x3000), # ori   s2,s2,0x3000
        r(5, 0, 2, 0x21),        # addu  v0,a1,zero
        j(0x03, LEAF),            # outer: jal leaf
        r(2, 7, 2, 0x2D),        # daddu v0,v0,a3 (delay)
        i(0x09, 16, 16, -1),     # addiu s0,s0,-1
        i(0x05, 16, 0, -4),      # bne   s0,zero,outer
        0,
        i(0x3F, 18, 2, 0),       # sd    v0,0(s2)
        i(0x2B, 18, 3, 8),       # sw    v1,8(s2)
        0x0000000D,              # break
    ]
    while ENTRY + len(words) * 4 < LEAF:
        words.append(0)
    words.extend([
        mmi(2, 5, 8, 0x13, 0x09),   # pxor  t0,v0,a1
        mmi(8, 6, 8, 0x12, 0x29),   # por   t0,t0,a2
        mmi(8, 7, 8, 0x12, 0x09),   # pand  t0,t0,a3
        r(2, 8, 2, 0x2D),           # daddu v0,v0,t0
        r(2, 6, 2, 0x2F),           # dsubu v0,v0,a2
        r(17, 0, 9, 0x21),          # addu  t1,s1,zero
        r(18, 0, 10, 0x21),         # addu  t2,s2,zero
        i(0x09, 0, 11, 8),          # addiu t3,zero,8
        i(0x37, 9, 12, 0),          # copy: ld t4,0(t1)
        i(0x3F, 10, 12, 0),         # sd    t4,0(t2)
        i(0x09, 9, 9, 8),           # addiu t1,t1,8
        i(0x09, 10, 10, 8),         # addiu t2,t2,8
        i(0x09, 11, 11, -1),        # addiu t3,t3,-1
        i(0x05, 11, 0, -6),         # bne   t3,zero,copy
        0,
        i(0x23, 17, 12, 0),         # lw    t4,0(s1)
        i(0x23, 17, 13, 4),         # lw    t5,4(s1)
        r(12, 13, 3, 0x18),         # mult  t4,t5,v1
        i(0x23, 17, 14, 8),         # lw    t6,8(s1)
        i(0x23, 17, 15, 12),        # lw    t7,12(s1)
        r(14, 15, 14, 0x18),        # mult  t6,t7,t6
        r(3, 14, 3, 0x21),          # addu  v1,v1,t6
        i(0x23, 17, 14, 16),        # lw    t6,16(s1)
        i(0x23, 17, 15, 20),        # lw    t7,20(s1)
        r(14, 15, 14, 0x18),        # mult  t6,t7,t6
        r(3, 14, 3, 0x21),          # addu  v1,v1,t6
        r(2, 3, 2, 0x2D),           # daddu v0,v0,v1
        r(31, 0, 0, 0x08),          # jr    ra
        0,
    ])
    return tuple(words)


def build_elf(words: tuple[int, ...]) -> bytes:
    code = struct.pack(f"<{len(words)}I", *words)
    image = bytearray(0x100 + len(code))
    ident = b"\x7fELF\x01\x01\x01" + bytes(9)
    image[:52] = struct.pack(
        "<16sHHIIIIIHHHHHH",
        ident, 2, 8, 1, ENTRY, 52, 0, 0, 52, 32, 1, 0, 0, 0,
    )
    image[52:84] = struct.pack(
        "<IIIIIIII", 1, 0x100, ENTRY, ENTRY, len(code), len(code), 5, 16
    )
    image[0x100:] = code
    return bytes(image)


def build_header(words: tuple[int, ...]) -> str:
    values = ",\n".join(f"    0x{word:08X}u" for word in words)
    return f"""// Generated by tools/make_aot_benchmark_elf.py. Do not edit.
#pragma once

#include <array>
#include <cstdint>

namespace ps2vita::benchmark_program {{
inline constexpr std::uint32_t kEntry = 0x{ENTRY:08X}u;
inline constexpr std::uint32_t kSource = 0x{SOURCE:08X}u;
inline constexpr std::uint32_t kDestination = 0x{DESTINATION:08X}u;
inline constexpr std::array<std::uint32_t, {len(words)}> kWords{{{{
{values}
}}}};
}} // namespace ps2vita::benchmark_program
"""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=Path)
    parser.add_argument("--header", required=True, type=Path)
    args = parser.parse_args()
    words = build_words()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(build_elf(words))
    args.header.write_text(build_header(words), encoding="utf-8", newline="\n")
    print(f"wrote {len(words)} benchmark instructions to {args.output}")


if __name__ == "__main__":
    main()
